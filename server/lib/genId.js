const crypto = require("crypto");

// Идентификатор записи: префикс, время и случайный хвост.
//
// Раньше id складывался из одного Date.now() (`m_${Date.now()}` и подобное).
// Два действия в одну миллисекунду — а под настоящей нагрузкой это обычное
// дело: два сообщения, две регистрации, два чата разом — давали одинаковый
// первичный ключ, и второй INSERT падал с ошибкой. При одном пользователе не
// видно; при набеге людей это первые же 500-е.
//
// Время впереди — чтобы id по-прежнему росли во времени (сортировка, порядок
// вставки), а случайные 40 бит в хвосте делают совпадение в одну миллисекунду
// практически невозможным. Формат остаётся «<префикс>_…», поэтому проверки
// вида id.startsWith("c_") (routes/stories.js) продолжают работать.
function genId(prefix) {
  return `${prefix}_${Date.now().toString(36)}${crypto.randomBytes(5).toString("hex")}`;
}

module.exports = { genId };
