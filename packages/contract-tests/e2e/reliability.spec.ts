import { test, expect } from "./support/fixtures";
import { createDm, login, sendText } from "../support/seed";
import { composer, expectSignedIn, messageText, sendMessage } from "./support/ui";
import { profilePanel } from "./social/helpers";

test("блокировка в открытом чате убирает смайл из шапки; сообщения остаются только у отправителя", async ({ newUser, openAs }) => {
  const alice = await newUser("Алиса");
  const boris = await newUser("Борис");
  expect((await boris.api.patch(`/api/users/${boris.id}`, { avatarEmoji: "🌻" })).status).toBe(200);
  const chat = await createDm(alice, boris);
  await sendText(boris, chat.id, "Переписка до блокировки");
  const a = (await openAs(alice.api, `/chat/${chat.id}`)).page;
  const b = (await openAs(boris.api, `/chat/${chat.id}`)).page;
  await expect(a.getByRole("banner").getByText("🌻", { exact: true })).toBeVisible();
  await b.getByRole("banner").getByRole("button", { name: /Алиса/ }).click();
  const info = profilePanel(b);
  await info.getByRole("button", { name: /Заблокировать/ }).click();
  await expect(info.getByRole("button", { name: /Разблокировать/ })).toBeVisible();
  await expect(a.getByRole("banner").getByText("🌻", { exact: true })).toHaveCount(0);
  await sendMessage(a, "Это сообщение собеседник не увидит");
  await composer(a).press("Enter");
  await expect(messageText(a, "Это сообщение собеседник не увидит")).toBeVisible();
  await expect.poll(async () => (await alice.api.get(`/api/chats/${chat.id}/messages`)).body.messages.filter((m: any) => m.text === "Это сообщение собеседник не увидит").length).toBe(1);
  await expect(messageText(b, "Это сообщение собеседник не увидит")).toHaveCount(0);
  await info.getByRole("button", { name: /Разблокировать/ }).click();
  await expect(a.getByRole("banner").getByText("🌻", { exact: true })).toBeVisible();
  await b.reload();
  await expect(messageText(b, "Переписка до блокировки")).toBeVisible();
  await expect(messageText(b, "Это сообщение собеседник не увидит")).toHaveCount(0);
  await sendMessage(a, "Новое сообщение после разблокировки");
  await expect(messageText(b, "Новое сообщение после разблокировки")).toBeVisible();
});

test("ответ на одном устройстве останавливает остальные, включая пропустившее ответ и перезагрузившееся", async ({ newUser, openAs, baseUrl }) => {
  const alice = await newUser("Алиса");
  const boris = await newUser("Борис");
  const chat = await createDm(alice, boris);
  const a = (await openAs(alice.api, `/chat/${chat.id}`)).page;
  const b = (await openAs(boris.api)).page;
  const phone = await openAs(await login(baseUrl, boris));
  const sleeping = await openAs(await login(baseUrl, boris));
  for (const page of [b, phone.page, sleeping.page]) await expectSignedIn(page);
  await a.getByRole("banner").getByRole("button", { name: "Позвонить", exact: true }).click();
  const incoming = (page: typeof b) => page.getByRole("dialog", { name: "Входящий звонок", exact: true });
  for (const page of [b, phone.page, sleeping.page]) await expect(incoming(page)).toBeVisible();
  await sleeping.context.setOffline(true);
  let answers = 0;
  b.on("request", (req) => { if (req.method() === "POST" && /\/api\/calls\/[^/]+\/answer$/.test(req.url())) answers++; });
  await b.getByRole("button", { name: "Ответить", exact: true }).click({ clickCount: 2 });
  await expect(b).toHaveURL(/\/call\//);
  await expect(incoming(phone.page)).toHaveCount(0);
  await sleeping.context.setOffline(false);
  await expect(incoming(sleeping.page)).toHaveCount(0);
  await phone.page.reload();
  await expectSignedIn(phone.page);
  await expect(incoming(phone.page)).toHaveCount(0);
  expect(answers).toBe(1);
  await a.getByRole("button", { name: "Завершить", exact: true }).click();
  await expect(b.getByRole("button", { name: "Завершить", exact: true })).toHaveCount(0);
});
