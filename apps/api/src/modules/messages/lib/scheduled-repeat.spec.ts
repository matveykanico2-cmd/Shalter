// Повторы отложенных сообщений. Ожидания сняты со старого server/data/scheduledMessages.js
// перед его удалением: сроки уже записанных повторов не должны сдвинуться.
import { describe, expect, it } from "vitest";
import { nextOccurrence, REPEATS, WHEN_ONLINE } from "./scheduled-repeat.js";

const NOW = "2026-03-15T12:00:00.000Z";
const BASES = ["2026-01-31T09:30:00.000Z", "2025-02-28T23:59:59.000Z", "2024-02-29T00:00:00.000Z", "2026-03-15T12:00:00.000Z", "не дата"];
const KINDS = [...REPEATS, "bogus"];

describe("повторы отложенных", () => {
  it("REPEATS и WHEN_ONLINE", () => {
    expect(REPEATS).toEqual(["day", "week", "2weeks", "month", "3months", "6months", "year"]);
    expect(WHEN_ONLINE).toBe("9999-12-31T00:00:00.000Z");
  });

  it("nextOccurrence: конец месяца, високосный год, срок уже прошёл, мусор", () => {
    expect(BASES.map((b) => KINDS.map((k) => nextOccurrence(b, k, NOW)))).toEqual([
      ["2026-03-16T09:30:00.000Z", "2026-03-21T09:30:00.000Z", "2026-03-28T09:30:00.000Z", "2026-03-31T09:30:00.000Z", "2026-04-30T09:30:00.000Z", "2026-07-31T09:30:00.000Z", "2027-01-31T09:30:00.000Z", null],
      ["2026-03-15T23:59:59.000Z", "2026-03-20T23:59:59.000Z", "2026-03-27T23:59:59.000Z", "2026-03-28T23:59:59.000Z", "2026-05-28T23:59:59.000Z", "2026-08-28T23:59:59.000Z", "2027-02-28T23:59:59.000Z", null],
      ["2026-03-16T00:00:00.000Z", "2026-03-19T00:00:00.000Z", "2026-03-26T00:00:00.000Z", "2026-03-29T00:00:00.000Z", "2026-05-29T00:00:00.000Z", "2026-08-29T00:00:00.000Z", "2027-02-28T00:00:00.000Z", null],
      ["2026-03-16T12:00:00.000Z", "2026-03-22T12:00:00.000Z", "2026-03-29T12:00:00.000Z", "2026-04-15T12:00:00.000Z", "2026-06-15T12:00:00.000Z", "2026-09-15T12:00:00.000Z", "2027-03-15T12:00:00.000Z", null],
      [null, null, null, null, null, null, null, null],
    ]);
  });
});
