import { getState, setState } from "../state.js";

// Кладёт только что появившееся сообщение в строку списка чатов — сразу, не
// дожидаясь следующего ответа GET /api/chats.
//
// Зачем это нужно. Превью в списке жило исключительно на ответе сервера, и у
// него было два слепых пятна:
//
// 1. Своё отправленное сообщение сервер обратно по сокету не присылает
//    (routes/messages.js, broadcastToOtherMembers — отправитель и так видит
//    его у себя). chatView.js после отправки обновлял только ленту сообщений,
//    поэтому строка в списке оставалась прежней до следующего опроса — до 15
//    секунд. В только что заведённом чате с ботом это выглядит буквально так:
//    открытая переписка с «/start», а рядом в списке — «Нет сообщений».
// 2. Чужое сообщение по сокету запускало refetch с задержкой в четверть
//    секунды, и ещё столько же ехал ответ; а если запрос списка не удался
//    (сеть моргнула, 429 от лимитера), превью не обновлялось вовсе, хотя само
//    сообщение уже пришло и отрисовано в чате.
//
// Черновики такую синхронизацию уже делали (chatView.js's handleDraftChange) —
// с настоящими сообщениями это ровно тот же приём. Ответ сервера, когда
// приедет, всё равно останется истиной в последней инстанции: здесь правится
// только превью, а счётчики непрочитанного и порядок закрепления досчитает
// refetch.
export function noteMessageInChatList(chatId, message) {
  // Ответы в ветке обсуждения в списке не показываются — сервер их из сводки
  // тоже исключает (chat-summary.js's `threadRootId IS NULL`).
  if (!message?.createdAt || message.threadRootId) return;

  const { chats } = getState();
  const target = chats.find((c) => c.id === chatId);
  // Чата ещё нет в списке (только что создан на другом устройстве) — его
  // принесёт обычный refetch, здесь дописывать его нечем.
  if (!target) return;
  // Не откатываем список назад: пока событие шло, ответ сервера мог принести
  // сообщение посвежее.
  if (target.lastMessage && target.lastMessage.createdAt > message.createdAt) return;

  setState({
    chats: chats.map((c) => (c.id === chatId ? { ...c, lastMessage: message } : c)),
  });
}
