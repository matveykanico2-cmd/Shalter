// Одно место, где живёт «какого качества картинку мы отправляем» — для звонков
// (lib/callController.js) и для эфиров (lib/liveController.js).
//
// Зачем отдельный модуль: раньше камера бралась запросом `video: true` (или
// голым facingMode), то есть на усмотрение браузера, — а браузеры по умолчанию
// дают 640×480 при 30 кадрах. Просить 1080p60 нужно в трёх местах (камера,
// переворот камеры, демонстрация экрана) и в двух сценариях (звонок, эфир);
// разъехавшись, эти шесть точек дали бы разное качество в звонке и в эфире.

// ideal, а не exact: `exact` — это требование, и на ноутбучной вебке без 60 fps
// getUserMedia просто падает с OverconstrainedError, то есть «нет камеры
// вообще». С ideal браузер отдаёт лучшее из того, что у него есть, и на слабой
// камере всё продолжает работать — просто в её собственном разрешении.
//
// Просим 4K 60. Что при этом честно знать:
//
// - 4K отдадут немногие камеры. Обычная вебка вернёт своё максимальное
//   разрешение, и это не поломка, а как раз то, ради чего здесь ideal.
// - Даже когда камера отдаёт 4K, до собеседника оно дойдёт только если канал и
//   процессор потянут: 4K60 — это порядка 20 Мбит/с и тяжёлое кодирование.
//   WebRTC меряет канал сам и опускается ниже, если не тянет; потолок ниже
//   поднят под этот случай, но потолок — это разрешение, а не обещание.
// - Телефон на 4K60 греется и сажает батарею быстрее. Это плата за требование,
//   а не недоделка.
export const HD_VIDEO = {
  // 1280×720 при 30 кадрах — то, что тянет обычное устройство и обычный канал.
  //
  // Здесь стояло 4K при 60 кадрах, и это была причина рывков в звонках: чтобы
  // отдать такую картинку, надо кодировать восемь миллионов точек шестьдесят
  // раз в секунду. Ни телефон, ни ноутбук без отдельного кодировщика этого не
  // успевают: кадры копятся в очереди, картинка идёт скачками и отстаёт от
  // звука, а телефон греется и садится.
  //
  // 720p — не потолок, а отправная точка: браузер сам поднимет качество, если
  // увидит, что канал и процессор справляются (см. degradationPreference ниже),
  // и опустит, если нет. Начинать с недостижимого и падать оттуда хуже, чем
  // начать с надёжного и подняться.
  width: { ideal: 1280 },
  height: { ideal: 720 },
  frameRate: { ideal: 60 },
};

// Экран просят в тех же 4K60. cursor: "motion" — курсор виден только когда
// движется; на статичном слайде он не мозолит глаза, а при показе действия
// остаётся на месте.
export const HD_SCREEN = {
  video: { ...HD_VIDEO, cursor: "motion" },
  // Звук вкладки/системы — если браузер и выбранный источник это умеют. Отказ
  // не мешает: демонстрация продолжится без звука.
  audio: false,
};

export function cameraConstraints(extra = {}) {
  return { ...HD_VIDEO, ...extra };
}

// Одного разрешения в constraints мало.
//
// Попросить у камеры 1080p и получить 1080p у собеседника — разные вещи: WebRTC
// сам решает, чем жертвовать при нехватке канала, и по умолчанию первым делом
// уменьшает картинку. Здесь поднят потолок битрейта и явно сказано, что
// сохранять важнее.
//
// maintain-resolution — по результату замера, а не по общим соображениям. На
// двух headless-браузерах через локальную петлю (то есть при заведомо широком
// канале) вариант «беречь кадры» — degradationPreference: maintain-framerate
// плюс contentHint: motion — отдавал зрителю 640×360 при источнике 1920×1080:
// кодек считал, что 60 кадров важнее, и уменьшал картинку сам, без всякой
// нехватки полосы. С maintain-resolution и contentHint: detail до зрителя
// доходили честные 1920×1080 — и с камеры, и с экрана.
//
// Обратная сторона осознанная: на узком канале просядут кадры, а не чёткость.
// Для показа экрана это правильный размен (текст должен читаться), для лица в
// звонке — спорный, но 1080p просили именно как 1080p.
//
// Если браузер не умеет setParameters (или сендер ещё не готов) — молча
// пропускаем: это украшение поверх работающего звонка, а не его условие.
export async function tuneVideoSender(sender, { screen = false } = {}) {
  if (!sender || sender.track?.kind !== "video" || typeof sender.getParameters !== "function") return;
  try {
    const params = sender.getParameters();
    if (!params.encodings || !params.encodings.length) params.encodings = [{}];
    // Потолок под 4K: на 4 Мбит/с, которых хватало для 1080p, картинка в
    // 3840×2160 превращается в кашу из квадратов — пикселей вчетверо больше, а
    // битов на них столько же. Это именно потолок: занимать его целиком WebRTC
    // будет только если канал позволяет, на узком он сам опустится ниже.
    // Потолок под 720p, а не под 4K: прежние двенадцать мегабит в секунду
    // означали, что кодировщик пытается занять канал, которого нет, и картинка
    // рассыпалась при первом же сужении полосы.
    // Шестьдесят кадров требуют больше битов, чем тридцать: картинок в секунду
    // вдвое больше, и на прежнем потолке они получались бы вдвое грязнее.
    params.encodings[0].maxBitrate = screen ? 5_000_000 : 3_500_000;
    params.encodings[0].maxFramerate = 60;
    // scaleResolutionDownBy намеренно не трогаем.
    //
    // Раньше он тут принудительно сбрасывался в единицу — «отправляй в полном
    // разрешении». Это отбирало у браузера последний способ разгрузиться:
    // уменьшить картинку он не мог и вместо этого ронял кадры. Вместе с
    // maintain-resolution выше это и давало рывки. Пусть решает сам.
    // maintain-framerate — «плавность важнее числа точек».
    //
    // Это прямая противоположность тому, что стояло раньше и вызывало рывки.
    // Там было maintain-resolution: держи 4K любой ценой — и ценой оказывались
    // кадры, разговор шёл скачками.
    //
    // Теперь наоборот: при нехватке канала или процессора браузер уменьшает
    // картинку, но продолжает отдавать шестьдесят кадров. Лицо в кадре
    // читается плавным движением, а не количеством точек: мягче, но ровно —
    // лучше, чем чётко, но рывками.
    //
    // Работает это только потому, что отправная точка посильная. 720p при 60
    // кадрах — вдевятеро меньше работы, чем 4K при тех же 60, и обычное
    // устройство с этим справляется.
    params.degradationPreference = screen ? "maintain-resolution" : "maintain-framerate";
    await sender.setParameters(params);
  } catch {
    // Старый браузер или дорожка уже сменилась — качество останется на
    // усмотрение браузера, что ровно то, как было до этого модуля.
  }
}

// Пройтись по всем видеосендерам соединения. Вызывается после каждого
// addTrack/replaceTrack: параметры живут на сендере, а не на дорожке, но
// сбрасываются при пересоздании соединения.
export function tunePeerVideo(pc, opts = {}) {
  if (!pc || typeof pc.getSenders !== "function") return;
  for (const sender of pc.getSenders()) {
    if (sender.track?.kind === "video") tuneVideoSender(sender, opts);
  }
}

// Подсказка кодеку, что за содержимое в дорожке. Для экрана — "detail": там
// мелкий текст и резкие границы, и кодек должен беречь их, а не плавность.
// "motion" (противоположная подсказка) на замере роняла картинку до 640×360,
// см. длинный комментарий выше.
export function hintScreenTrack(track) {
  // "detail" бережёт чёткость мелкого текста ценой плавности — для показа
  // кода или документа это верно. Если демонстрация начнёт дёргаться так же,
  // как дёргалось видео, здесь нужно ставить "motion".
  if (track && "contentHint" in track) track.contentHint = "detail";
}
