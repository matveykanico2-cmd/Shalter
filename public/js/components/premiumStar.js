import { el } from "../lib/dom.js";

// Знак Premium — золотисто-оранжевая звезда, как настоящий значок в
// Telegram (не белая звезда на цветном квадрате, как было раньше, и не
// шесть случайных цветных вариантов — у Telegram один узнаваемый золотой
// цвет, и разнообразие тут только мешало узнаванию).
//
// PREMIUM_VARIANTS оставлен пустым массивом (не удалён совсем) ради
// обратной совместимости: несколько мест в коде вызывают PremiumStar с
// variant: "gold"/"violet" — они по-прежнему работают, просто variant
// больше ничего не меняет визуально, звезда всегда одна и та же.
export const PREMIUM_VARIANTS = ["gold"];

// Звезда рисуется один раз на вызов и вставляется строкой — как остальные
// значки в icons.js. Пользовательский ввод сюда не попадает.
//
// Три слоя: сама звезда (градиент светлого золота вверху → глубокого
// оранжевого внизу, по диагонали — так выглядит настоящий значок Premium),
// лёгкая тень на правой половине для объёма (плоская заливка иначе читается
// как наклейка, не как объект), и маленькая искра-блик сверху слева.
//
// Градиенты — через <defs> с id, а id в инлайновом SVG виден всему
// документу разом: без уникального суффикса несколько звёзд на одном экране
// (PremiumStarRow, лента чатов) стали бы ссылаться на один и тот же
// <linearGradient>, и часть рисовалась бы неправильно. uid делает каждый
// вызов независимым.
let uidCounter = 0;
function starSvg(uid) {
  return `
<svg viewBox="0 0 24 24" aria-hidden="true" class="ps-star">
  <defs>
    <linearGradient id="ps-fill-${uid}" x1="0.1" y1="0" x2="0.8" y2="1">
      <stop offset="0%" stop-color="#ffc93b"/>
      <stop offset="55%" stop-color="#ff9f1a"/>
      <stop offset="100%" stop-color="#ff7a00"/>
    </linearGradient>
  </defs>
  <path d="M12 1.8l2.95 6.4 7 .75-5.2 4.8 1.45 6.9L12 16.85 5.8 20.65l1.45-6.9-5.2-4.8 7-.75Z"
    fill="url(#ps-fill-${uid})"/>
  <!-- Тень на правой половине звезды — от центра-низа по контуру до
       верхней точки и прямой линией обратно к центру, то есть ровно правая
       половина силуэта — даёт объём вместо плоской наклейки. -->
  <path d="M12 1.8l2.95 6.4 7 .75-5.2 4.8 1.45 6.9L12 16.85V1.8Z" fill="#7a2e00" fill-opacity="0.18"/>
  <path d="M8.6 5.6c.3 1.15 1.1 1.95 2.25 2.25-1.15.3-1.95 1.1-2.25 2.25-.3-1.15-1.1-1.95-2.25-2.25 1.15-.3 1.95-1.1 2.25-2.25Z"
    fill="#fff" fill-opacity="0.9"/>
</svg>`;
}

// size — размер значка в пикселях. variant больше не влияет на цвет (см.
// комментарий выше), параметр остался только чтобы старые вызовы не ломались.
export function PremiumStar({ size = 22, variant, seed = "", title = "Premium", className = "" } = {}) {
  const uid = `${Date.now().toString(36)}${uidCounter++}`;
  const box = el("span", {
    class: `premium-star ${className}`,
    title,
    style: `width:${size}px; height:${size}px`,
    html: starSvg(uid),
  });
  return box;
}

// Раньше показывала шесть цветных вариантов — теперь такого понятия нет
// (см. выше), поэтому просто одна звезда покрупнее для заглавной картинки
// страницы Premium. Оставлена отдельной функцией, а не инлайном на месте
// вызова, чтобы не трогать settings/index.js там, где она уже используется.
export function PremiumStarRow({ size = 64 } = {}) {
  return el("div", { class: "premium-star-row" }, [PremiumStar({ size, title: "Shalter Premium" })]);
}
